export type GameTextKey = keyof typeof ENGLISH_TEXT;
export type GameTextVariables = Record<string, string | number>;

function interpolate(template: string, variables?: GameTextVariables) {
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    key in variables ? String(variables[key]) : placeholder
  );
}

export function translateGameText(
  locale: string,
  source: GameTextKey,
  variables?: GameTextVariables
): string {
  const template =
    normalizeGameLocale(locale) === "en" ? ENGLISH_TEXT[source] : source;
  return interpolate(template, variables);
}
